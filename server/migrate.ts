/// <reference types="node" />
/**
 * `paseo-kanban migrate`: copy a board from the legacy `data/` beside the plugin into Paseo's
 * plugin-data directory, roll that copy back, or finish it once the observation period is over.
 *
 * Copy, never move. The old directory is only read, its database included: kanban.db and its WAL
 * are copied as raw files and snapshotted (VACUUM INTO) from that copy, because even a read-only
 * SQLite open of a WAL database leaves -wal/-shm files beside it. Steps that change the new
 * directory run with the plugin disabled. MIGRATION.json in the new directory records what was
 * copied, so doctor, rollback and finish can check that nothing was lost.
 */
