function integrity(db: DatabaseSync): string {
  const rows = db.prepare("PRAGMA integrity_check").all() as Array<{ integrity_check: string }>;
  return rows.map(row => row.integrity_check).join("; ");
}

function diffRows(expected: Record<string, TableRows>, actual: Record<string, TableRows>): string[] {
  const names = new Set([...Object.keys(expected), ...Object.keys(actual)]);
  return [...names].sort().filter(name => expected[name]?.count !== actual[name]?.count || expected[name]?.maxId !== actual[name]?.maxId)
    .map(name => `${name}: ${expected[name]?.count ?? "-"} rows / max id ${expected[name]?.maxId ?? "-"} -> ${actual[name]?.count ?? "-"} / ${actual[name]?.maxId ?? "-"}`);
}

/** The old database files present now, with their stamps. */
function sourceDbState(dir: string, hash: boolean): { stamps: Record<string, FileStamp>; present: string[] } {
  const stamps: Record<string, FileStamp> = {};
  for (const name of DB_CONTENT_FILES) {
    const stamp = stampOf(join(dir, name), hash);
    if (stamp) stamps[name] = stamp;
  }
  return { stamps, present: DB_FILES.filter(name => occupied(join(dir, name))) };
}

/**
 * Raw-copy kanban.db (and its -wal/-journal) into the backup, open that copy, VACUUM INTO the
 * snapshot, then check the snapshot: integrity_check and every table's row count and MAX(id).
 */
function snapshotDatabase(from: string, backupDir: string): { rows: Record<string, TableRows>; sha256: string } {
  const raw = join(backupDir, ".source-db");
  mkdirSync(raw, { mode: DIR_MODE });
  const snapshot = join(backupDir, DB_FILE);
  let sourceRows: Record<string, TableRows>;
  try {
    for (const name of DB_CONTENT_FILES) {
      if (existsSync(join(from, name))) copyFileSync(join(from, name), join(raw, name), constants.COPYFILE_FICLONE);
    }
    const copy = new DatabaseSync(join(raw, DB_FILE));
    try {
      copy.exec("PRAGMA busy_timeout = 5000");
      sourceRows = tableRows(copy);
      copy.prepare("VACUUM INTO ?").run(snapshot);
    } finally {
      copy.close();
    }
  } finally {
    rmSync(raw, { recursive: true, force: true });
  }
  chmodSync(snapshot, FILE_MODE);
  const db = new DatabaseSync(snapshot, { readOnly: true });
  let rows: Record<string, TableRows>;
  try {
    const check = integrity(db);
    if (check !== "ok") throw new KanbanError("conflict", `The database snapshot failed integrity_check: ${check}`);
    rows = tableRows(db);
  } finally {
    db.close();
  }
  const diff = diffRows(sourceRows, rows);
  if (diff.length > 0) throw new KanbanError("conflict", `The database snapshot does not match the old database: ${diff.join("; ")}`);
  return { rows, sha256: sha256File(snapshot) };
}

