function missing(err: unknown): boolean {
  return (err as NodeJS.ErrnoException).code === "ENOENT";
}

/** Every entry under `root` with its lstat. One that disappears while it is listed is left out. */
function walk(root: string, at = ""): Array<{ path: string; stat: Stats }> {
  let names: string[];
  try {
    names = readdirSync(join(root, ...at.split("/"))).sort();
  } catch (err) {
    if (at && missing(err)) return [];
    throw err;
  }
  const out: Array<{ path: string; stat: Stats }> = [];
  for (const name of names) {
    const path = at ? `${at}/${name}` : name;
    let stat: Stats;
    try {
      stat = lstatSync(join(root, ...path.split("/")));
    } catch (err) {
      if (missing(err)) continue;
      throw err;
    }
    out.push({ path, stat });
    if (stat.isDirectory()) out.push(...walk(root, path));
  }
  return out;
}

function skipReason(path: string): string | null {
  if (path === `${DB_FILE}-wal` || path === `${DB_FILE}-journal`) return "folded into the kanban.db snapshot";
  if (path === `${DB_FILE}-shm`) return "SQLite index, rebuilt when the database opens";
  if (path === MIGRATION_FILE) return "record of an earlier migration, not carried over";
  // The board writes through `<file>.<pid>...tmp` and renames; one left behind is an interrupted write.
  if (path.endsWith(".tmp")) return "temporary file of an interrupted write";
  return null;
}

/**
 * Where a copied symlink points under `root` (the backup or the new directory): a link into the old
 * directory at the same path under `root`, a link out of it at the same outside target as before.
 */
function migratedLink(path: string, linkTarget: string, from: string, root: string): string {
  const absolute = resolve(dirname(join(from, ...path.split("/"))), linkTarget);
  const real = canonicalPath(absolute);
  if (!inside(real, from)) return isAbsolute(linkTarget) ? linkTarget : absolute;
  const inRoot = join(root, relative(from, real));
  return isAbsolute(linkTarget) ? inRoot : relative(dirname(join(root, ...path.split("/"))), inRoot) || ".";
}

/** Conflicts in the target besides the files to copy: database leftovers and an earlier migration's record. */
function targetConflicts(to: string): Array<{ path: string; reason: string }> {
  const out: Array<{ path: string; reason: string }> = [];
  if (leavesTarget(join(to, BACKUPS_DIR, "migration-<timestamp>"), to)) out.push({ path: `${BACKUPS_DIR}/`, reason: "a link out of the target; the backup would land elsewhere" });
  for (const name of DB_FILES.slice(1)) {
    if (occupied(join(to, name))) out.push({ path: name, reason: "leftover database file; SQLite would apply it to the new kanban.db" });
  }
  if (occupied(join(to, MIGRATION_FILE))) out.push({ path: MIGRATION_FILE, reason: "an earlier migration is still recorded here; roll it back or finish it first" });
  return out;
}

/** What a migration from `fromInput` to `toInput` would copy. Reads only. */
export function planMigration(fromInput: string, toInput: string): MigrationPlan {
  const to = resolve(toInput);
  assertTestDataPath(resolve(fromInput));
  assertTestDataPath(to);
  if (!isDirectory(fromInput)) throw new KanbanError("not_found", `--from ${resolve(fromInput)} is not a directory.`);
  // The real path: the record, the checks and the archive are about the directory, not a link to it.
  const from = canonicalPath(fromInput);
  if (!occupied(join(from, DB_FILE)) || !lstatSync(join(from, DB_FILE)).isFile()) throw new KanbanError("not_found", `${from} has no ${DB_FILE}; nothing to migrate.`);
  if (inside(canonicalPath(to), from) || inside(from, canonicalPath(to))) throw new KanbanError("invalid", `--from ${from} and --to ${to} must be separate directories, neither inside the other.`);
  if (occupied(to) && !isDirectory(to)) throw new KanbanError("invalid", `--to ${to} exists and is not a directory.`);
  const targetBefore = occupied(to) ? readdirSync(to).sort() : [];
  const plan: MigrationPlan = { from, to, entries: [], skipped: [], conflicts: [], unknown: [], totalBytes: 0, targetBefore };
  for (const { path, stat } of walk(from)) {
    if (stat.isDirectory()) continue;
    const reason = skipReason(path) ?? (stat.isFile() || stat.isSymbolicLink() ? null : "not a regular file or symlink");
    if (reason) {
      plan.skipped.push({ path, reason });
      continue;
    }
    const known = KNOWN_FILES.some(pattern => pattern.test(path));
    const kind = path === DB_FILE ? "database" : stat.isSymbolicLink() ? "symlink" : "file";
    const target = join(to, ...path.split("/"));
    plan.entries.push({ path, kind, size: stat.size, target, known });
    plan.totalBytes += stat.size;
    if (!known) plan.unknown.push(path);
    if (leavesTarget(target, to)) plan.conflicts.push({ path, reason: "a directory on the way is a link out of the target" });
    else if (!path.startsWith(`${EXPORTS_DIR}/`) && occupied(target)) plan.conflicts.push({ path, reason: "already exists in the target" });
  }
  if (occupied(to)) plan.conflicts.push(...targetConflicts(to));
  return plan;
}

export function formatPlan(plan: MigrationPlan): string {
  const lines = [
    "Dry run: nothing was written.",
    `From: ${plan.from}`,
    `To:   ${plan.to}`,
    `Would copy ${plan.entries.length} files (${formatBytes(plan.totalBytes)}):`,
    ...plan.entries.map(entry => `  ${entry.path}  ${formatBytes(entry.size)}  -> ${entry.target}${entry.kind === "database" ? "  (snapshot via VACUUM INTO)" : ""}${entry.kind === "symlink" ? "  (symlink)" : ""}${entry.known ? "" : "  (unknown file)"}`),
  ];
  if (plan.skipped.length > 0) lines.push("Not copied:", ...plan.skipped.map(item => `  ${item.path}  (${item.reason})`));
  if (plan.unknown.length > 0) lines.push(`Unknown files, copied and listed in ${MIGRATION_FILE}: ${plan.unknown.join(", ")}`);
  lines.push(plan.conflicts.length === 0 ? "Conflicts: none" : "Conflicts (a real run refuses until these are moved away):", ...plan.conflicts.map(item => `  ${item.path}  (${item.reason})`));
  lines.push(`A real run disables the plugin (paseo plugin disable ${PLUGIN_ID}), backs up into ${join(plan.to, BACKUPS_DIR, "migration-<timestamp>")}, copies and verifies, writes ${MIGRATION_FILE} and enables the plugin again. The old directory is not changed.`);
  return lines.join("\n");
}

