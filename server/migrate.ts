// Command line

export const MIGRATE_HELP = `Usage:
  paseo-kanban migrate --from <old data directory> [--to <data directory>] [--dry-run] [--json]
  paseo-kanban migrate --rollback <timestamp> [--to <data directory>] [--json]
  paseo-kanban migrate --finish <timestamp> [--to <data directory>] [--json]

--to defaults to $PASEO_HOME/plugin-data/${PLUGIN_ID} (~/.paseo when PASEO_HOME is not set).
--dry-run lists the files, sizes, target paths and conflicts, and writes nothing.
A migration disables the plugin, snapshots kanban.db with VACUUM INTO, copies every other file
(the old directory is never changed), checks integrity and row counts, writes MIGRATION.json and
enables the plugin. --rollback exports what was added since, moves the new files into
backups/rollback-<timestamp>/ so the plugin uses the old directory again. --finish archives the
old directory into backups/legacy-<timestamp>.tar(.zst) and deletes the migrated files from it,
only after the observation check passes: tasks and events have not lost rows or MAX(id), and the
old directory is as the migration left it. Rollback refuses too when the old directory changed.`;

export function runMigrateCli(argv: string[], env: NodeJS.ProcessEnv = process.env, deps: MigrateDeps = defaultMigrateDeps(env)): { json: boolean; result: unknown; text: string } {
  const { values } = parseArgs({
    args: argv,
    options: {
      from: { type: "string" }, to: { type: "string" }, "dry-run": { type: "boolean" },
      rollback: { type: "string" }, finish: { type: "string" }, json: { type: "boolean" }, help: { type: "boolean", short: "h" },
    },
    strict: true,
    allowPositionals: false,
  });
  const json = values.json === true;
  if (values.help) return { json: false, result: MIGRATE_HELP, text: MIGRATE_HELP };
  const modes = [values.from, values.rollback, values.finish].filter(value => value !== undefined);
  if (modes.length !== 1) throw new KanbanError("invalid", `Give exactly one of --from, --rollback, --finish.\n${MIGRATE_HELP}`);
  if (values["dry-run"] && values.from === undefined) throw new KanbanError("invalid", "--dry-run only goes with --from.");
  const to = values.to?.trim() || defaultPluginDataDir(env);
  if (values.from !== undefined) {
    const result = migrate({ from: values.from, to, dryRun: values["dry-run"] === true }, deps);
    return { json, result, text: result.text };
  }
  if (values.rollback !== undefined) {
    const result = rollbackMigration({ to, stamp: values.rollback }, deps);
    return { json, result, text: result.text };
  }
  const result = finishMigration({ to, stamp: values.finish ?? "" }, deps);
  return { json, result, text: result.text };
}

/**
 * Every step runs synchronously, so with a handler installed Ctrl-C or SIGTERM is only handled once
 * the step and its `paseo plugin enable` are done, instead of killing the run with the plugin disabled.
 */
function deferSignals(): void {
  for (const signal of ["SIGINT", "SIGTERM", "SIGHUP"] as const) {
    process.on(signal, () => console.error(`${signal} received; it took effect only after the migration step had finished.`));
  }
}

const invoked = process.argv[1] ? pathToFileURL(process.argv[1]).href : "";
if (import.meta.url === invoked) {
  deferSignals();
  try {
    const { json, result, text } = runMigrateCli(process.argv.slice(2));
    console.log(json ? JSON.stringify(result, null, 2) : text);
  } catch (err) {
    const payload = err instanceof KanbanError ? err.toJSON() : { ok: false, message: message(err) };
    console.error(process.argv.includes("--json") ? JSON.stringify(payload) : message(err));
    process.exit(1);
  }
}
