export const ROLLBACK_SCHEMA = "paseo-kanban/rollback/v1";
const BACKUPS_DIR = "backups";
/** Contract exports are regenerated by the plugin: files there are overwritten, never a conflict. */
const EXPORTS_DIR = "exports";
const PASEO_TIMEOUT_MS = 120_000;
/** Error code when there is no paseo command at all: enabling cannot work either. */
const PASEO_MISSING = "paseo_missing";
const HOLDER_WAIT_MS = 10_000;
const HOLDER_POLL_MS = 250;
const DIR_MODE = 0o700;
const FILE_MODE = 0o600;

/** §3.1 of the publishing design plus the files the board writes beside its database. Anything else is copied and listed as unknown. */
const KNOWN_FILES: readonly RegExp[] = [
  /^kanban\.db$/, /^kanban\.config\.json$/, /^supervisor\.token$/, /^mcp\.port$/, /^doctor-report\.json$/,
  /^exports\//, /^backups\//, /^readonly-leftovers\//, /^kanban\.db\.bak-[^/]+$/, /^kanban\.config\.[^/]+$/,
  /^(board-wake-marks|daemon-restart|scheduler-tick|perf-summary|missing-cwd-registered)\.json$/,
  /^missing-cwd-list\.md$/, /^config\.lock\.db$/,
];

export interface PlanEntry {
  path: string;
  kind: "database" | "file" | "symlink";
  size: number;
  target: string;
  known: boolean;
}

export interface MigrationPlan {
  from: string;
  to: string;
  entries: PlanEntry[];
  skipped: Array<{ path: string; reason: string }>;
  conflicts: Array<{ path: string; reason: string }>;
  unknown: string[];
  totalBytes: number;
  targetBefore: string[];
}

/** Stops and starts the plugin around a step that changes its data. */
export interface PluginControl {
  disable(): void;
  enable(): void;
}

export interface MigrateDeps {
  plugin: PluginControl;
  listHolders: HolderLister;
  now: () => Date;
  /** Waits between holder checks. Tests pass a no-op. */
  sleep: (ms: number) => void;
}

// ---------------------------------------------------------------------------------------------
// Small file helpers

function posix(path: string): string {
  return path.split(sep).join("/");
}

function message(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

/** A directory, or a symlink to one. */
function isDirectory(path: string): boolean {
  try {
    return statSync(path).isDirectory();
  } catch {
    return false;
  }
}

/** Something already sits at this path, including a file where a parent directory should be. */
function occupied(path: string): boolean {
  try {
    lstatSync(path);
    return true;
  } catch (err) {
    return (err as NodeJS.ErrnoException).code !== "ENOENT";
  }
}

function writeJsonAtomic(path: string, value: unknown): void {
  const tmp = `${path}.${process.pid}.tmp`;
  writeFileSync(tmp, `${JSON.stringify(value, null, 2)}\n`, { mode: FILE_MODE });
  renameSync(tmp, path);
}

/** mkdir -p that remembers which directories it created, so a failed run can remove them again. */
function ensureDir(path: string, created: string[]): void {
  if (existsSync(path)) return;
  ensureDir(dirname(path), created);
  mkdirSync(path, { mode: DIR_MODE });
  created.push(path);
}

function inside(child: string, parent: string): boolean {
  const rel = relative(parent, child);
  return rel === "" || (!isAbsolute(rel) && rel !== ".." && !rel.startsWith(`..${sep}`));
}

/**
 * A path written under the target must land in the target's own tree. A directory on the way that
 * is a link elsewhere (exports/ or backups/ pointing into the old directory, say) would carry the
 * write out of it, so the real location of the parent is checked, not the spelling.
 */
function leavesTarget(path: string, to: string): boolean {
  return !inside(canonicalPath(dirname(path)), canonicalPath(to));
}

function assertInTarget(paths: string[], to: string): void {
  const outside = paths.filter(path => leavesTarget(path, to));
  if (outside.length > 0) throw new KanbanError("conflict", `These would be written outside ${to} through a linked directory: ${outside.join(", ")}. Nothing was changed.`);
}

export function formatStamp(date: Date): string {
  return date.toISOString().replace(/\.\d{3}Z$/, "Z").replace(/[-:]/g, "");
}

function assertStamp(stamp: string): void {
  if (!STAMP_PATTERN.test(stamp)) throw new KanbanError("invalid", `Not a migration timestamp: ${stamp}. Expected the form 20261008T070000Z printed by migrate.`);
}

