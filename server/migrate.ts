/** `paseo plugin disable|enable paseo-kanban`, against PASEO_HOME's daemon when it is set. */
export function paseoPluginControl(env: NodeJS.ProcessEnv = process.env, command = "paseo"): PluginControl {
  const run = (action: "disable" | "enable") => {
    const home = env.PASEO_HOME?.trim();
    const args = ["plugin", action, PLUGIN_ID, ...(home ? ["--home", home] : [])];
    const shown = `${command} ${args.join(" ")}`;
    const out = spawnSync(command, args, { encoding: "utf8", env, timeout: PASEO_TIMEOUT_MS });
    if (out.error) {
      if ((out.error as NodeJS.ErrnoException).code === "ENOENT") {
        throw new KanbanError(PASEO_MISSING, `The paseo command was not found on PATH, so the plugin could not be ${action}d. Install the Paseo CLI or put it on PATH, then run again. (${shown})`);
      }
      throw new KanbanError("unavailable", `${shown} failed: ${out.error.message}`);
    }
    if (out.status !== 0) {
      const detail = `${out.stderr ?? ""}${out.stdout ?? ""}`.trim();
      throw new KanbanError("unavailable", `${shown} exited with ${out.status ?? out.signal}${detail ? `: ${detail}` : ""}`);
    }
  };
  return { disable: () => run("disable"), enable: () => run("enable") };
}

/** `lsof` is the only way to see another process's handle on the database; no answer means stop. */
function listHoldersWithLsof(files: string[]): ReturnType<HolderLister> {
  try {
    return lsofHolders(files);
  } catch {
    throw new KanbanError("unavailable", "lsof could not run, so there is no telling whether another process still has the database open. Install lsof (or put it on PATH) and run again.");
  }
}

export function defaultMigrateDeps(env: NodeJS.ProcessEnv = process.env): MigrateDeps {
  const pause = new Int32Array(new SharedArrayBuffer(4));
  return { plugin: paseoPluginControl(env), listHolders: listHoldersWithLsof, now: () => new Date(), sleep: ms => Atomics.wait(pause, 0, 0, ms) };
}

/** The plugin's process can take a moment to exit after disable; any other holder means stop. */
function waitForNoHolders(dir: string, deps: Pick<MigrateDeps, "listHolders" | "sleep">): void {
  const files = DB_FILES.map(name => join(dir, name));
  for (let attempt = 1; ; attempt++) {
    const holders = deps.listHolders(files);
    if (holders.length === 0) return;
    if (attempt * HOLDER_POLL_MS >= HOLDER_WAIT_MS) {
      const who = holders.map(holder => `${holder.command} (pid ${holder.pid})`).join(", ");
      throw new KanbanError("conflict", `${join(dir, DB_FILE)} is still open by ${who}. Stop that process and run again.`, { holders });
    }
    deps.sleep(HOLDER_POLL_MS);
  }
}

/** Disable, run, enable. A failed step still enables the plugin, and its error is the one reported. */
function withPluginDisabled<T>(deps: MigrateDeps, work: () => T, onFailure: () => string = () => ""): T {
  try {
    deps.plugin.disable();
  } catch (err) {
    const code = err instanceof KanbanError ? err.code : "unavailable";
    // The daemon may have disabled the plugin before the command failed (a timeout, say): enable it to be sure.
    let enableNote = "";
    if (code !== PASEO_MISSING) {
      try {
        deps.plugin.enable();
      } catch (enableErr) {
        enableNote = ` Enabling the plugin to be sure failed too (${message(enableErr)}); check paseo plugin ls.`;
      }
    }
    throw new KanbanError(code, `${message(err)} Stopped before changing any data.${enableNote}`);
  }
  let result: T;
  try {
    result = work();
  } catch (err) {
    const undone = onFailure();
    let enableNote = "";
    try {
      deps.plugin.enable();
    } catch (enableErr) {
      enableNote = ` Enabling the plugin again also failed (${message(enableErr)}); run: paseo plugin enable ${PLUGIN_ID}`;
    }
    const code = err instanceof KanbanError ? err.code : "conflict";
    throw new KanbanError(code, `${message(err)}${undone ? ` ${undone}` : ""}${enableNote}`);
  }
  try {
    deps.plugin.enable();
  } catch (err) {
    throw new KanbanError("unavailable", `The data step finished, but the plugin could not be enabled again: ${message(err)}. Run: paseo plugin enable ${PLUGIN_ID}`);
  }
  return result;
}

