function copyEntry(entry: PlanEntry, from: string, backupDir: string, dest: string): ManifestEntry {
  const source = join(from, ...entry.path.split("/"));
  const stat = lstatSync(source);
  const base = { path: entry.path, size: stat.size, mode: stat.mode & 0o777, mtimeMs: stat.mtimeMs, known: entry.known };
  if (entry.kind === "symlink") {
    const linkTarget = readlinkSync(source);
    symlinkSync(migratedLink(entry.path, linkTarget, from, backupDir), dest);
    return { ...base, kind: "symlink", sha256: null, linkTarget };
  }
  const sha256 = sha256File(source);
  copyFileSync(source, dest, constants.COPYFILE_FICLONE);
  chmodSync(dest, base.mode);
  const copied = sha256File(dest);
  if (copied !== sha256) throw new KanbanError("conflict", `The copy of ${entry.path} does not match the original (sha256 ${sha256} vs ${copied}).`);
  return { ...base, kind: "file", sha256 };
}

/** Copy one backed-up file into the target through a temporary name, then check it. */
function installEntry(entry: ManifestEntry, from: string, backupDir: string, to: string, created: string[], placed: string[]): void {
  const parts = entry.path.split("/");
  const backup = join(backupDir, ...parts);
  const dest = join(to, ...parts);
  assertInTarget([dest], to);
  ensureDir(dirname(dest), created);
  const existed = occupied(dest);
  const tmp = `${dest}.migrating-${process.pid}`;
  if (entry.kind === "symlink") symlinkSync(migratedLink(entry.path, entry.linkTarget ?? "", from, to), tmp);
  else {
    copyFileSync(backup, tmp, constants.COPYFILE_FICLONE);
    chmodSync(tmp, entry.mode);
    const copied = sha256File(tmp);
    if (copied !== entry.sha256) {
      unlinkSync(tmp);
      throw new KanbanError("conflict", `The installed copy of ${entry.path} does not match the original.`);
    }
  }
  renameSync(tmp, dest);
  if (!existed) placed.push(dest);
}

/** Remove what a failed run put into the target. Exports it overwrote are regenerated by the plugin. */
function undoInstall(placed: string[], created: string[]): string {
  const left: string[] = [];
  for (const path of [...placed].reverse()) {
    try {
      unlinkSync(path);
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== "ENOENT") left.push(path);
    }
  }
  for (const dir of [...created].reverse()) {
    try {
      rmdirSync(dir);
    } catch {
      // Not empty (it holds the backup) or already gone.
    }
  }
  return left.length > 0 ? `Could not remove from the target: ${left.join(", ")}.` : "";
}

export interface MigrateResult {
  dryRun: boolean;
  plan: MigrationPlan;
  record: MigrationRecord | null;
  text: string;
}

/** What a real run changed in the target so far, for undoing it after a failure. */
interface InstallTrail {
  created: string[];
  placed: string[];
  backupDir: string | null;
}

function conflictError(plan: MigrationPlan): KanbanError {
  const list = plan.conflicts.map(item => `  ${item.path}  (${item.reason})`).join("\n");
  return new KanbanError("conflict", `The target already has files the migration would write. Nothing was changed.\n${list}`, { conflicts: plan.conflicts });
}

/** The whole real run, between disable and enable. Returns the record it wrote and the file list it used. */
function copyAndVerify(planned: MigrationPlan, stamp: string, now: Date, deps: MigrateDeps, trail: InstallTrail): { record: MigrationRecord; plan: MigrationPlan } {
  const { created, placed } = trail;
  waitForNoHolders(planned.from, deps);
  // The plugin wrote until it stopped: list the files again now that nothing else writes them.
  const plan = planMigration(planned.from, planned.to);
  if (plan.conflicts.length > 0) throw conflictError(plan);
  const { from, to } = plan;
  const backupRel = `${BACKUPS_DIR}/migration-${stamp}`;
  const backupDir = join(to, BACKUPS_DIR, `migration-${stamp}`);
  assertInTarget([backupDir], to);
  ensureDir(join(to, BACKUPS_DIR), created);
  if (occupied(backupDir)) throw new KanbanError("conflict", `${backupDir} already exists; run again in a second.`);
  mkdirSync(backupDir, { mode: DIR_MODE });
  trail.backupDir = backupDir;
  const before = sourceDbState(from, true);
  const snapshot = snapshotDatabase(from, backupDir);
  const moved = sourceDbChanges(from, before.stamps, true);
  if (moved.length > 0) throw new KanbanError("conflict", `The old database changed while it was copied (${moved.join("; ")}). Something still writes to it; stop it and run again.`);
  const files: ManifestEntry[] = [];
  for (const entry of plan.entries) {
    if (entry.kind === "database") continue;
    const dest = join(backupDir, ...entry.path.split("/"));
    assertInTarget([dest], to);
    ensureDir(dirname(dest), created);
    files.push(copyEntry(entry, from, backupDir, dest));
  }
  for (const entry of files) installEntry(entry, from, backupDir, to, created, placed);
  // The database goes in last: its presence is what makes the plugin choose this directory.
  const tmpDb = join(to, `${DB_FILE}.migrating-${process.pid}`);
  copyFileSync(join(backupDir, DB_FILE), tmpDb, constants.COPYFILE_FICLONE);
  chmodSync(tmpDb, FILE_MODE);
  placed.push(tmpDb);
  if (sha256File(tmpDb) !== snapshot.sha256) throw new KanbanError("conflict", "The installed kanban.db does not match the snapshot.");
  const installed = diffRows(snapshot.rows, readRows(tmpDb));
  if (installed.length > 0) throw new KanbanError("conflict", `The installed kanban.db does not match the old database: ${installed.join("; ")}`);
  const record: MigrationRecord = {
    schema: MIGRATION_SCHEMA,
    timestamp: stamp,
    migratedAt: now.toISOString(),
    source: from,
    target: to,
    backup: backupRel,
    state: "active",
    database: { file: DB_FILE, source: before.stamps, present: before.present, snapshotSha256: snapshot.sha256, integrity: "ok" },
    rows: snapshot.rows,
    files,
    unknownFiles: plan.unknown,
    skipped: plan.skipped,
    targetBefore: plan.targetBefore,
  };
  // The record goes first: a run killed right after the rename still leaves something rollback can act on.
  writeJsonAtomic(join(to, MIGRATION_FILE), record);
  placed.push(join(to, MIGRATION_FILE));
  renameSync(tmpDb, join(to, DB_FILE));
  placed.push(join(to, DB_FILE));
  return { record, plan };
}

export function migrate(options: { from: string; to: string; dryRun: boolean }, deps: MigrateDeps): MigrateResult {
  const planned = planMigration(options.from, options.to);
  if (options.dryRun) return { dryRun: true, plan: planned, record: null, text: formatPlan(planned) };
  // Refuse before touching the plugin; the list is made again once the plugin has stopped.
  if (planned.conflicts.length > 0) throw conflictError(planned);
  const now = deps.now();
  const stamp = formatStamp(now);
  const trail: InstallTrail = { created: [], placed: [], backupDir: null };
  const { record, plan } = withPluginDisabled(deps, () => copyAndVerify(planned, stamp, now, deps, trail), () => {
    const left = undoInstall(trail.placed, trail.created);
    const partial = trail.backupDir && existsSync(trail.backupDir) ? ` The partial backup stays in ${trail.backupDir}.` : "";
    return `The old directory was not changed.${partial}${left ? ` ${left}` : ""}`;
  });
  const counts = ["tasks", "events"].map(name => `${name} ${record.rows[name]?.count ?? 0} (max id ${record.rows[name]?.maxId ?? "-"})`).join(", ");
  const text = [
    `Migrated ${plan.from} -> ${plan.to} (timestamp ${stamp}).`,
    `Copied ${record.files.length} files and the database; integrity_check ok; rows ${counts}.`,
    `Backup: ${join(plan.to, record.backup)}. Record: ${join(plan.to, MIGRATION_FILE)}.`,
    `The old directory was not changed. Roll back with: paseo-kanban migrate --rollback ${stamp} --to ${plan.to}`,
    `After the observation period: paseo-kanban migrate --finish ${stamp} --to ${plan.to}`,
  ].join("\n");
  return { dryRun: false, plan, record, text };
}

// ---------------------------------------------------------------------------------------------
// Rollback and finish act on the active record

function activeRecord(to: string, stamp: string): MigrationRecord {
  assertStamp(stamp);
  assertTestDataPath(to);
  const record = readMigrationRecord(to);
  if (!record) throw new KanbanError("not_found", `${to} has no ${MIGRATION_FILE}: no migration to act on.`);
  if (record.timestamp !== stamp) throw new KanbanError("conflict", `The migration recorded in ${to} is ${record.timestamp}, not ${stamp}.`);
  if (record.state !== "active") throw new KanbanError("conflict", `Migration ${stamp} is already ${record.state}.`);
  // The directory the record sits in is the target, even if it was renamed since.
  return { ...record, target: to };
}

function describeProblems(problems: ObservationProblem[]): string {
  return problems.map(problem => `  [${problem.severity}] ${problem.detail}`).join("\n");
}

// ---------------------------------------------------------------------------------------------
// Rollback

export interface RollbackResult {
  record: MigrationRecord;
  exportFile: string;
  movedTo: string;
  moved: string[];
  newRows: Record<string, number>;
  text: string;
}

/**
 * Rows added since the migration (id above the recorded MAX(id)), and older cards changed since.
 * A migration killed before its database was renamed into place has nothing to export.
 */
function exportSince(to: string, record: MigrationRecord, now: Date): { body: Record<string, unknown>; counts: Record<string, number> } {
  const file = join(to, DB_FILE);
  const head = { schema: ROLLBACK_SCHEMA, migration: record.timestamp, exportedAt: now.toISOString(), since: record.rows };
  if (!occupied(file)) return { body: { ...head, database: null, newRows: {}, changedTasks: [] }, counts: {} };
  const db = new DatabaseSync(file, { readOnly: true });
  try {
    db.exec("PRAGMA busy_timeout = 5000");
    const current = tableRows(db);
    const newRows: Record<string, unknown[]> = {};
    const counts: Record<string, number> = {};
    for (const [table, before] of Object.entries(record.rows)) {
      if (before.maxId === null || !current[table]) continue;
      newRows[table] = db.prepare(`SELECT * FROM ${quoteIdent(table)} WHERE id > ? ORDER BY id`).all(before.maxId);
      counts[table] = newRows[table].length;
    }
    const tasksMax = record.rows.tasks?.maxId ?? 0;
    const changedTasks = current.tasks ? db.prepare("SELECT * FROM tasks WHERE id <= ? AND updated_at > ? ORDER BY id").all(tasksMax, record.migratedAt) : [];
    counts.changedTasks = changedTasks.length;
    return { body: { ...head, database: file, newRows, changedTasks }, counts };
  } finally {
    db.close();
  }
}

/** Remove empty directories under and including `dir`, deepest first. Files are never touched. */
function removeEmptyDirs(dir: string): void {
  if (!isDirectory(dir) || lstatSync(dir).isSymbolicLink()) return;
  for (const name of readdirSync(dir)) removeEmptyDirs(join(dir, name));
  try {
    rmdirSync(dir);
  } catch {
    // Not empty.
  }
}

/** Put back what a failed rollback moved (kanban.db, moved first, goes back last) and drop its export. */
function undoRollback(moves: Array<[string, string]>, exportFile: string, movedTo: string): string {
  const stuck: string[] = [];
  for (const [from, to] of [...moves].reverse()) {
    try {
      mkdirSync(dirname(from), { recursive: true, mode: DIR_MODE });
      renameSync(to, from);
    } catch (err) {
      stuck.push(`${to} (${message(err)})`);
    }
  }
  rmSync(exportFile, { force: true });
  rmSync(join(movedTo, MIGRATION_FILE), { force: true });
  removeEmptyDirs(movedTo);
  return stuck.length === 0
    ? "Everything it moved was put back; the migrated board is still the one in use."
    : `Could not put back: ${stuck.join("; ")}. Move those back by hand before running the rollback again.`;
}

/** Refuse a rollback onto an old directory that is not as the migration left it, or has no board at all. */
function assertRollbackTarget(record: MigrationRecord): void {
  if (!occupied(join(record.source, DB_FILE))) {
    throw new KanbanError("conflict", `The old directory has no ${DB_FILE} any more (${record.source}); rolling back would leave the plugin with an empty board. Nothing was changed.`);
  }
  const stale = oldDirProblems(record, true);
  if (stale.length > 0) {
    throw new KanbanError("conflict", `The old directory is no longer as the migration left it, so the rollback would not return to what was migrated. Nothing was changed.\n${describeProblems(stale)}`);
  }
}

export function rollbackMigration(options: { to: string; stamp: string }, deps: MigrateDeps): RollbackResult {
  const to = resolve(options.to);
  const record = activeRecord(to, options.stamp);
  assertRollbackTarget(record);
  const exportFile = join(to, BACKUPS_DIR, `rollback-${record.timestamp}.json`);
  const movedTo = join(to, BACKUPS_DIR, `rollback-${record.timestamp}`);
  assertInTarget([exportFile, movedTo], to);
  if (occupied(exportFile) || occupied(movedTo)) throw new KanbanError("conflict", `${exportFile} or ${movedTo} already exists. Nothing was changed.`);
  const keep = new Set([BACKUPS_DIR, EXPORTS_DIR, MIGRATION_FILE, ...record.targetBefore]);
  const moves: Array<[string, string]> = [];
  const move = (path: string) => {
    const parts = path.split("/");
    mkdirSync(join(movedTo, ...parts.slice(0, -1)), { recursive: true, mode: DIR_MODE });
    renameSync(join(to, ...parts), join(movedTo, ...parts));
    moves.push([join(to, ...parts), join(movedTo, ...parts)]);
  };
  const now = deps.now();
  const exported = withPluginDisabled(deps, () => {
    waitForNoHolders(to, deps);
    const changed = sourceDbChanges(record.source, record.database.source, false);
    if (changed.length > 0) throw new KanbanError("conflict", `The old database changed just now (${changed.join("; ")}). Something still writes to it.`);
    const { body, counts } = exportSince(to, record, now);
    writeJsonAtomic(exportFile, body);
    // kanban.db first: once it is gone the plugin chooses the old directory again.
    const names = readdirSync(to).filter(name => !keep.has(name)).sort((a, b) => Number(b === DB_FILE) - Number(a === DB_FILE));
    for (const name of names) move(name);
    // Migrated files inside directories the target already had (exports/, backups/ or its own).
    for (const entry of record.files) {
      const top = entry.path.split("/")[0] ?? "";
      if (entry.path.includes("/") && keep.has(top) && occupied(join(to, ...entry.path.split("/")))) move(entry.path);
    }
    const done: MigrationRecord = {
      ...record, state: "rolled-back", rolledBackAt: now.toISOString(), rollbackExport: posix(relative(to, exportFile)),
      rollbackDir: posix(relative(to, movedTo)),
    };
    writeJsonAtomic(join(movedTo, MIGRATION_FILE), done);
    unlinkSync(join(to, MIGRATION_FILE));
    return { done, counts };
  }, () => undoRollback(moves, exportFile, movedTo));
  const text = [
    `Rolled back migration ${record.timestamp}. The plugin uses ${record.source} again.`,
    `New since the migration: ${Object.entries(exported.counts).map(([name, n]) => `${name} ${n}`).join(", ") || "nothing"}; exported to ${exportFile} for manual replay.`,
    `The new directory's files moved to ${movedTo} (nothing deleted).`,
    "The old directory was checked unchanged.",
  ].join("\n");
  return { record: exported.done, exportFile, movedTo, moved: moves.map(([from]) => posix(relative(to, from))), newRows: exported.counts, text };
}

// ---------------------------------------------------------------------------------------------
// Finish

function hasCommand(command: string): boolean {
  const out = spawnSync(command, ["--version"], { stdio: "ignore" });
  return !out.error && out.status === 0;
}

function runTool(command: string, args: string[]): string {
  // COPYFILE_DISABLE keeps macOS tar from adding ._ AppleDouble entries.
  const out = spawnSync(command, args, { encoding: "utf8", maxBuffer: 256 * 1024 * 1024, env: { ...process.env, COPYFILE_DISABLE: "1" } });
  if (out.error || out.status !== 0) throw new KanbanError("conflict", `${command} ${args.join(" ")} failed: ${out.error?.message ?? out.stderr.trim()}`);
  return out.stdout;
}

/** tar the whole old directory, check every recorded file is in it, then zstd it when zstd exists. */
function archiveSource(record: MigrationRecord, to: string): string {
  const tar = join(to, BACKUPS_DIR, `legacy-${record.timestamp}.tar`);
  assertInTarget([tar], to);
  if (occupied(tar) || occupied(`${tar}.zst`)) throw new KanbanError("conflict", `${tar}(.zst) already exists. Nothing was changed.`);
  const top = basename(record.source);
  runTool("tar", ["-cf", tar, "-C", dirname(record.source), top]);
  chmodSync(tar, FILE_MODE);
  const listed = new Set(runTool("tar", ["-tf", tar]).split("\n").map(line => line.replace(/\/$/, "")));
  const wanted = [...record.files.map(entry => entry.path), ...record.database.present];
  const missing = wanted.filter(path => !listed.has(`${top}/${path}`));
  if (missing.length > 0) {
    unlinkSync(tar);
    throw new KanbanError("conflict", `The archive is missing ${missing.join(", ")}. Nothing was deleted.`);
  }
  if (!hasCommand("zstd")) return tar;
  try {
    runTool("zstd", ["-q", tar, "-o", `${tar}.zst`]);
    runTool("zstd", ["-q", "-t", `${tar}.zst`]);
  } catch {
    // The verified .tar is enough; a half-written .zst would only block the next finish.
    rmSync(`${tar}.zst`, { force: true });
    return tar;
  }
  chmodSync(`${tar}.zst`, FILE_MODE);
  unlinkSync(tar);
  return `${tar}.zst`;
}

export interface FinishResult {
  record: MigrationRecord;
  archive: string;
  removed: string[];
  left: string[];
  text: string;
}

export function finishMigration(options: { to: string; stamp: string }, deps: Pick<MigrateDeps, "now" | "listHolders" | "sleep">): FinishResult {
  const to = resolve(options.to);
  const record = activeRecord(to, options.stamp);
  assertTestDataPath(record.source);
  // Any problem refuses: fewer rows or a lower MAX(id) in either table, an unreadable board, a changed old directory.
  const problems = checkObservation(record, { hash: true });
  if (problems.length > 0) {
    throw new KanbanError("conflict", `The observation check did not pass, so the old directory stays. Nothing was changed.\n${describeProblems(problems)}`, { problems });
  }
  // A process that still has the old board open would write into deleted files.
  waitForNoHolders(record.source, deps);
  const archive = archiveSource(record, to);
  const removed: string[] = [];
  for (const path of [...record.files.map(entry => entry.path), ...record.database.present]) {
    try {
      unlinkSync(join(record.source, ...path.split("/")));
      removed.push(path);
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw new KanbanError("conflict", `Could not delete ${path} from ${record.source}: ${message(err)}. Removed so far: ${removed.join(", ") || "none"}. The archive is ${archive}.`);
    }
  }
  const dirs = [...new Set(removed.flatMap(path => path.split("/").slice(0, -1).map((_, i, parts) => parts.slice(0, i + 1).join("/"))))];
  for (const dir of dirs.sort((a, b) => b.length - a.length)) {
    try {
      rmdirSync(join(record.source, ...dir.split("/")));
    } catch {
      // Still holds files the migration did not copy.
    }
  }
  const left = existsSync(record.source) ? walk(record.source).filter(item => !item.stat.isDirectory()).map(item => item.path) : [];
  const now = deps.now();
  const done: MigrationRecord = {
    ...record, state: "finished", finishedAt: now.toISOString(), legacyArchive: posix(relative(to, archive)), removedFromSource: removed, leftInSource: left,
  };
  writeJsonAtomic(join(to, MIGRATION_FILE), done);
  const days = ((now.getTime() - Date.parse(record.migratedAt)) / 86_400_000).toFixed(1);
  const text = [
    `Finished migration ${record.timestamp} (${days} days after it). The observation check passed. Old directory archived to ${archive}.`,
    `Deleted ${removed.length} migrated files from ${record.source}.${left.length > 0 ? ` Left there (not part of the migration): ${left.join(", ")}.` : ""}`,
  ].join("\n");
  return { record: done, archive, removed, left, text };
}

